/*
# Create secure e-Mola license purchase requests

1. New table: `license_purchase_requests`
- `id`: public request identifier generated by the database.
- `customer_name`: customer name supplied during the request.
- `license_type`: `monthly`, `yearly`, or `lifetime`.
- `amount_mzn`: fixed amount validated against the selected license.
- `payment_method`: fixed as `e-mola` by the database.
- `payment_number`: fixed as `865831887` by the database.
- `transfer_holder_name`: name shown on the transfer.
- `transaction_reference`: optional transfer reference.
- `receipt_path`: private Storage object path, when a receipt is attached.
- `status`: `pending_verification`, `approved`, or `rejected`.
- `created_at`, `reviewed_at`, `reviewed_by`, `review_notes`: review history fields.

2. Storage
- Creates private bucket `license-receipts`.
- Limits receipts to image formats and 5 MB.
- Anonymous clients may upload only into the `pending/` folder and cannot read, replace, or delete files.
- Administrative accounts may read receipts through short-lived signed URLs.

3. Security
- RLS is enabled on the request table.
- Anonymous clients can only create a pending request using the allowed customer fields.
- Anonymous clients cannot list, read, update, approve, reject, or delete requests.
- Authenticated users with `app_metadata.role = admin` can read requests and update only review fields.
- Prices, payment details, status, and review fields are protected by column privileges and database checks.

4. Important notes
- A receipt upload never approves or activates a license.
- Approval remains a manual administrative action.
- No existing rows are changed or deleted.
*/

CREATE TABLE IF NOT EXISTS public.license_purchase_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_name text NOT NULL,
  license_type text NOT NULL CHECK (license_type IN ('monthly', 'yearly', 'lifetime')),
  amount_mzn integer NOT NULL CHECK (
    (license_type = 'monthly' AND amount_mzn = 150) OR
    (license_type = 'yearly' AND amount_mzn = 250) OR
    (license_type = 'lifetime' AND amount_mzn = 1500)
  ),
  payment_method text NOT NULL DEFAULT 'e-mola' CHECK (payment_method = 'e-mola'),
  payment_number text NOT NULL DEFAULT '865831887' CHECK (payment_number = '865831887'),
  transfer_holder_name text NOT NULL,
  transaction_reference text,
  receipt_path text CHECK (receipt_path IS NULL OR receipt_path LIKE 'pending/%'),
  status text NOT NULL DEFAULT 'pending_verification' CHECK (status IN ('pending_verification', 'approved', 'rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id),
  review_notes text
);

ALTER TABLE public.license_purchase_requests ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.license_purchase_requests FROM anon, authenticated;
GRANT INSERT (customer_name, license_type, amount_mzn, transfer_holder_name, transaction_reference, receipt_path)
  ON TABLE public.license_purchase_requests TO anon;
GRANT SELECT ON TABLE public.license_purchase_requests TO authenticated;
GRANT UPDATE (status, reviewed_at, reviewed_by, review_notes)
  ON TABLE public.license_purchase_requests TO authenticated;

DROP POLICY IF EXISTS "Public can submit license requests" ON public.license_purchase_requests;
CREATE POLICY "Public can submit license requests"
ON public.license_purchase_requests FOR INSERT
TO anon
WITH CHECK (status = 'pending_verification' AND payment_method = 'e-mola' AND payment_number = '865831887');

DROP POLICY IF EXISTS "Admins can view license requests" ON public.license_purchase_requests;
CREATE POLICY "Admins can view license requests"
ON public.license_purchase_requests FOR SELECT
TO authenticated
USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

DROP POLICY IF EXISTS "Admins can review license requests" ON public.license_purchase_requests;
CREATE POLICY "Admins can review license requests"
ON public.license_purchase_requests FOR UPDATE
TO authenticated
USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
WITH CHECK (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  AND status IN ('pending_verification', 'approved', 'rejected')
);

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('license-receipts', 'license-receipts', false, 5242880, ARRAY['image/jpeg', 'image/png', 'image/webp'])
ON CONFLICT (id) DO UPDATE
SET public = false, file_size_limit = 5242880, allowed_mime_types = EXCLUDED.allowed_mime_types;

DROP POLICY IF EXISTS "Customers can upload pending receipts" ON storage.objects;
CREATE POLICY "Customers can upload pending receipts"
ON storage.objects FOR INSERT
TO anon
WITH CHECK (bucket_id = 'license-receipts' AND (storage.foldername(name))[1] = 'pending');

DROP POLICY IF EXISTS "Admins can read license receipts" ON storage.objects;
CREATE POLICY "Admins can read license receipts"
ON storage.objects FOR SELECT
TO authenticated
USING (
  bucket_id = 'license-receipts'
  AND (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);
